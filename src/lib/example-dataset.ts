const DEFAULT_PRIORITIES: SegmentCategory[] = PRIORITY_CARDS.map((c) => c.id);

const DEFAULT_ENABLED: SegmentCategory[] = [
  "long",
  "short",
  "placeholders",
  "markup",
  "numbers",
  "consistency",
];

export const DEMO_DATASET_ID = "demo-legal-en-de";

/**
 * A ready-made dataset that looks as though it was already produced by the
 * full create-challenge workflow. Used to seed the module on first load.
 */
export async function createDemoDataset(): Promise<ChallengeDataset> {
  const result = await extractDataset({
    rawSegments: EXAMPLE_RAW_SEGMENTS,
    sizeRange: "400-800",
    priorities: DEFAULT_PRIORITIES,
    enabledCriteria: DEFAULT_ENABLED,
    glossaryTerms: EXAMPLE_GLOSSARY_TERMS,
    hasGlossary: true,
  });

  return {
    id: DEMO_DATASET_ID,
    name: "Demo · Legal EN→DE Challenge",
    domain: "Legal",
    tags: ["demo", "en-de"],
    sourceLanguage: "EN",
    targetLanguage: "DE",
    sizeRange: "400-800",
    targetSize: result.targetSize,
    segmentCount: result.segments.length,
    sourceFileNames: ["legal-corpus.tmx", "ui-strings.xlsx"],
    glossaryFileName: "legal-glossary.csv",
    priorities: DEFAULT_PRIORITIES,
    enabledCriteria: DEFAULT_ENABLED,
    segments: result.segments,
    categoryBreakdown: result.categoryBreakdown,
    randomBaseCount: result.randomBaseCount,
    duplicateCount: result.duplicateCount,
    // Created a few days ago so it reads as pre-existing.
    createdAt: new Date(Date.now() - 3 * 24 * 60 * 60 * 1000).toISOString(),
  };
}
